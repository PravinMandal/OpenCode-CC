// Capture the canonical opencode request identity.
//
// The upstream free tier matches the exact system prompt and tool list the
// stock client sends, and the system prompt embeds the model name. The default
// is the DeepSeek model this deployment serves; set CAPTURE_MODELS to a
// comma-separated list to capture others explicitly.
//
// Run it again after upgrading opencode; the bridge picks the new capture up.
import { $ } from "bun";
import { chmod, mkdir, writeFile, readdir, rename } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";

const HOME = homedir();
const OUT_DIR = process.env.BRIDGE_IDENTITY_DIR ||
  join(HOME, ".local", "share", "opencode-native");
const PRIMARY_PATH = process.env.BRIDGE_IDENTITY || join(OUT_DIR, "identity.json");
const PRIMARY = "deepseek-v4.1-flash-free";
const ENDPOINT = "https://opencode.ai/inference/openai/v1/chat/completions";

// Refresh every model that already has a capture, not just the primary. A
// per-model prompt is generated by the stock client, so after an opencode
// upgrade the primary would be re-captured while glm-*/kimi-* kept an
// outdated canonical prompt forever.
async function existingModels() {
  try {
    const names = await readdir(OUT_DIR);
    return names
      .map(name => name.match(/^identity-(.+)\.json$/)?.[1])
      .filter(name => name && name.length <= 128 && !name.includes("..") &&
        /^[a-z0-9][a-z0-9._-]*$/.test(name));
  } catch {
    return [];
  }
}

const MODELS = (process.env.CAPTURE_MODELS
  ? process.env.CAPTURE_MODELS.split(",").map(m => m.trim()).filter(Boolean)
  : [...new Set([PRIMARY, ...(await existingModels())])]);

// Model names become filenames. Reject separators, overlong names and `..`
// before building an output path: a crafted CAPTURE_MODELS value must not
// write outside OUT_DIR or fail with ENAMETOOLONG after a partial run.
const MAX_MODEL_NAME_CHARS = 128;
const MODEL_NAME_RE = /^[a-z0-9][a-z0-9._-]*$/;
const validModel = model => model.length <= MAX_MODEL_NAME_CHARS &&
  MODEL_NAME_RE.test(model) && !model.includes("..");

const outPath = model => join(OUT_DIR, `identity-${model}.json`);

// A refresh walks every known model sequentially. Give each one a bounded
// slice of the wrapper's total budget instead of letting the head models
// consume all of it and SIGKILL the tail on every run.
const TOTAL_BUDGET_MS = Number(process.env.BRIDGE_CAPTURE_TIMEOUT_MS || 300_000);
const PER_MODEL_TIMEOUT_MS = Number(process.env.BRIDGE_CAPTURE_MODEL_TIMEOUT_MS ||
  Math.max(5_000, Math.floor((TOTAL_BUDGET_MS - 15_000) / Math.max(1, MODELS.length))));
const deadline = Date.now() + Math.max(1_000, TOTAL_BUDGET_MS - 10_000);

// The capture wrapper can be killed by transport.mjs on timeout. Bun's shell
// spawns opencode as a grandchild, so killing the wrapper alone left a hung
// opencode running. Spawn it in its own process group and kill the group.
let activeChild = null;
function killActiveChild(signal = "SIGKILL") {
  const child = activeChild;
  if (!child?.pid) return;
  try { process.kill(-child.pid, signal); }
  catch { try { child.kill(signal); } catch {} }
}
for (const sig of ["SIGTERM", "SIGINT"]) {
  process.on(sig, () => { killActiveChild("SIGKILL"); process.exit(1); });
}

let version = "unknown";
try {
  version = (await $.env({ ...process.env, OPENCODE_CONFIG_CONTENT: "" })`opencode --version`.text()).trim().split("\n")[0];
} catch {}

async function capture(model, timeoutMs) {
  if (!validModel(model)) return { model, ok: false, reason: "invalid model name" };
  const captured = { value: null };
  const server = Bun.serve({
    port: 0,
    hostname: "127.0.0.1",
    async fetch(req) {
      const url = new URL(req.url);
      if (!url.pathname.endsWith("/chat/completions")) return new Response("not found", { status: 404 });
      const raw = await req.text();
      if (!captured.value) {
        const parsed = JSON.parse(raw);
        const first = parsed.messages?.[0];
        const tools = parsed.tools || null;
        if (first?.role === "system" && typeof first.content === "string" && tools?.length) {
          captured.value = {
            system: first.content,
            tools,
            headers: Object.fromEntries(
              [...req.headers.entries()].filter(([k]) =>
                k === "user-agent" || k.startsWith("x-opencode") ||
                k === "x-session-affinity" || k === "x-session-id")),
          };
        }
      }
      const stream = new ReadableStream({
        start(c) {
          const chunk = { id: "c1", object: "chat.completion.chunk", created: 1, model,
            choices: [{ index: 0, delta: { role: "assistant", content: "ok" }, finish_reason: "stop" }] };
          c.enqueue(new TextEncoder().encode(`data: ${JSON.stringify(chunk)}\n\ndata: [DONE]\n\n`));
          c.close();
        },
      });
      return new Response(stream, { headers: { "content-type": "text/event-stream" } });
    },
  });

  const config = JSON.stringify({
    providers: { opencode: { settings: { baseURL: `http://127.0.0.1:${server.port}/v1` } } },
  });

  let timedOut = false;
  try {
    activeChild = Bun.spawn(
      ["opencode", "--standalone", "run", "--model", `opencode/${model}`,
        "--format", "json", "capture identity"],
      {
        env: { ...process.env, OPENCODE_CONFIG_CONTENT: config },
        stdin: "ignore",
        stdout: "ignore",
        stderr: "ignore",
        // Own process group: the timeout kill must reach opencode's children
        // too, not just this wrapper.
        detached: true,
      });
    const timer = setTimeout(() => {
      timedOut = true;
      killActiveChild("SIGKILL");
    }, Math.max(1_000, timeoutMs));
    try {
      await activeChild.exited;
    } finally {
      clearTimeout(timer);
    }
  } catch {
  } finally {
    activeChild = null;
  }

  server.stop(true);
  if (timedOut) return { model, ok: false, reason: "capture timeout" };
  if (!captured.value) return { model, ok: false, reason: "no canonical request observed" };

  const identity = {
    version,
    capturedAt: new Date().toISOString(),
    model,
    endpoint: ENDPOINT,
    system: captured.value.system,
    tools: captured.value.tools,
    headers: captured.value.headers,
  };
  // Write-then-rename: a crash mid-write must not leave a truncated identity
  // file that every later request parses as garbage and falls back from.
  const target = outPath(model);
  const tmp = `${target}.tmp-${process.pid}`;
  await writeFile(tmp, JSON.stringify(identity, null, 1) + "\n", { mode: 0o600 });
  await chmod(tmp, 0o600);
  await rename(tmp, target);
  return { model, ok: true, systemLen: identity.system.length, tools: identity.tools.length };
}

await mkdir(OUT_DIR, { recursive: true, mode: 0o700 });
try { await chmod(OUT_DIR, 0o700); } catch {}
const summary = [];
for (const model of MODELS) {
  const remaining = deadline - Date.now();
  if (remaining <= 0) {
    summary.push({ model, ok: false, reason: "capture budget exhausted" });
    continue;
  }
  summary.push(await capture(model, Math.min(PER_MODEL_TIMEOUT_MS, remaining)));
}

// identity.json stays the primary/default capture. Copy through a temp file
// so a concurrent request never reads a half-written fallback.
try {
  const primary = PRIMARY_PATH;
  const tmp = `${primary}.tmp-${process.pid}`;
  await writeFile(tmp, await Bun.file(outPath(PRIMARY)).text(), { mode: 0o600 });
  await chmod(tmp, 0o600);
  await rename(tmp, primary);
} catch {}

console.log(JSON.stringify({ ok: summary.every(s => s.ok), version, summary }, null, 1));
process.exit(summary.every(s => s.ok) ? 0 : 1);
